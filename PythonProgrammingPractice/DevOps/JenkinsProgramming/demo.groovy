// Devops - Combination of development + operational
// Bridge between developer and user
// Jenkins, Docker, Github, Ansible, Kubernetes
// Jenkins - A CICD (Continous Integration and Continous Deployment) that performs a series of steps to provide to a user automatically
// Jenkins can be coded in any scripting language (like HTML, groovy, bash script, shell script (python works, but it's not completely supported))
// Docker - A cloud repository which has a collection of base images and tools
// Docker works based on Docker Daemon
// Ansible - Provides a mechanism to connect between remote machines and local host
// Ansible is coded with a YAML language
// Kubernetes - Helps to manage Jenkins, Docker, and Ansible pods